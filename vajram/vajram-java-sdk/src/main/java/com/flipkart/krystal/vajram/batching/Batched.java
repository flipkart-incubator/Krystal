package com.flipkart.krystal.vajram.batching;

import static java.lang.annotation.ElementType.FIELD;
import static java.lang.annotation.ElementType.METHOD;
import static java.lang.annotation.RetentionPolicy.RUNTIME;

import com.flipkart.krystal.vajram.IOVajramDef;
import java.lang.annotation.Retention;
import java.lang.annotation.Target;

/**
 * A facet with this annotation is batched using an {@link InputBatcher} . This annotation can only
 * be used in {@link IOVajramDef}s. When a facet is marked as batched, the execution runtime invokes
 * the Output Logic of the IOVajram once for multiple requests by batching them into a collection.
 * This allows application developers to perform delegation operations like network IO, disk IO etc.
 * in an optimal fashion by batching the processing of multiple requests into a single IO operation.
 * This gives significant performance gains. Consequently, the application developers are expected
 * to return multiple results from the output logic (one for each item in the batch) as a map where
 * the value is the response corresponding to one request and the key is an object which contains
 * all the batch inputs (this class is auto-generated by the vajram code generator).
 *
 * <p>A {@code @Batched} facet can be an input, injection, dependency or field. It can be accessed
 * only via the batch items in the output logic and never individually. It cannot be combined with
 * {@link BatchesGroupedBy}.
 *
 * <p>Batching rules:
 *
 * <ol>
 *   <li>{@link Batched} can be placed on any facet. Such facets are read only via the batch items
 *       collection in the output logic. (In other logics, all facets are read individually)
 *   <li>{@link BatchesGroupedBy} can be placed only on given facets (inputs and injections).
 *   <li>Facets which are not {@link Batched} cannot depend, directly or indirectly, on {@link
 *       Batched} facets.
 *   <li>Facets which are not {@link Batched} are always accessed individually in the output logic
 *       (even inputs).
 *   <li>All given facets of a vajram which supports batching must have either {@link Batched} or
 *       {@link BatchesGroupedBy}.
 * </ol>
 *
 * <p>Together these guarantee that all facets which are not {@link Batched} have the same value for
 * all the requests in a batch: the given ones because they are batch keys, and the rest because
 * they are derived only from batch keys. Rules 2 and 5 and the facets which can be validated from
 * {@code @Resolve} and {@code @ComputeField} methods in rule 3 are validated at compile time. All
 * the rules are validated again when the vajram graph is loaded (which also covers resolvers
 * defined via {@code getSimpleInputResolvers()}).
 */
@Target({FIELD, METHOD})
@Retention(RUNTIME)
public @interface Batched {}
